"""
Information-theoretic payload discriminator for the Voynich "machine".

Question: after fitting the BEST mechanical model, does the manuscript retain an
irreducible residual "payload" (a real message run through a verbose cipher),
or does the machine essentially EXHAUST the text (self-generation)?

Method: held-out cross-entropy by physical-folio K-fold CV, applied by an
IDENTICAL pipeline to three corpora:
  (A) REAL manuscript
  (B) SELF-GEN floor  (corpora generated by the fitted machine)
  (C) CIPHER ceiling  (real English prose run through a verbose homophonic
                       cipher matched to the manuscript's marginals)

Read-only over the factorization TSV. All output stays under payload_mdl/.
numpy only, no GPU. Seeded.
"""
